/**
 * P1-1: categories.yml → categories.ts 코드젠
 * shared/docs/categories.yml 을 권위본으로 읽어
 * frontend/lib/constants/categories.ts 를 자동 생성한다.
 *
 * 사용:
 *   node scripts/gen-categories.mjs          # 생성
 *   node scripts/gen-categories.mjs --check  # drift 검사 (CI용)
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const jsYaml = require('js-yaml');

const __dirname = dirname(fileURLToPath(import.meta.url));
const yamlPath = resolve(__dirname, '../../shared/docs/categories.yml');
const outPath  = resolve(__dirname, '../lib/constants/categories.ts');
const isCheck  = process.argv.includes('--check');

// ─── YAML → TypeScript 변환 ──────────────────────────────────────────────────

function q(str) {
  // 작은따옴표 이스케이프
  return `'${String(str).replace(/'/g, "\\'")}'`;
}

function genMinors(minors, indent) {
  const pad = ' '.repeat(indent);
  return minors.map(m =>
    `${pad}{ id: ${q(m.id)}, label: ${q(m.label)}, allowCustomInput: ${m.allowCustomInput} },`
  ).join('\n');
}

function genMiddles(middles, indent) {
  const pad = ' '.repeat(indent);
  return middles.map(mid => {
    const lines = [
      `${pad}{`,
      `${pad}  id: ${q(mid.id)},`,
      `${pad}  label: ${q(mid.label)},`,
      `${pad}  minors: [`,
      genMinors(mid.minors ?? [], indent + 4),
      `${pad}  ],`,
      `${pad}},`,
    ];
    return lines.join('\n');
  }).join('\n');
}

function genCategories(majors) {
  return majors.map(maj => {
    const relationType = String(maj.relationType).toLowerCase();
    const lines = [
      '  {',
      `    id: ${q(maj.id)},`,
      `    label: ${q(maj.label)},`,
      `    relationType: ${q(relationType)},`,
      '    middles: [',
      genMiddles(maj.middles ?? [], 6),
      '    ],',
      '  },',
    ];
    return lines.join('\n');
  }).join('\n');
}

function buildFile(majors) {
  return [
    `// AUTO-GENERATED by scripts/gen-categories.mjs — do not edit manually`,
    `// Source: shared/docs/categories.yml`,
    `// Run: npm run gen:categories`,
    `import type { MajorCategory } from '@/lib/types';`,
    ``,
    `export const CATEGORIES: MajorCategory[] = [`,
    genCategories(majors),
    `];`,
    ``,
    `export function findMajor(id: string) {`,
    `  return CATEGORIES.find((m) => m.id === id);`,
    `}`,
    ``,
    `export function findMiddle(majorId: string, middleId: string) {`,
    `  return findMajor(majorId)?.middles.find((m) => m.id === middleId);`,
    `}`,
    ``,
    `export function findMinor(majorId: string, middleId: string, minorId: string) {`,
    `  return findMiddle(majorId, middleId)?.minors.find((m) => m.id === minorId);`,
    `}`,
    ``,
  ].join('\n');
}

// ─── 실행 ────────────────────────────────────────────────────────────────────

async function run() {
  let raw;
  try {
    raw = await readFile(yamlPath, 'utf-8');
  } catch (e) {
    if (e.code === 'ENOENT') {
      console.log('[gen-categories] categories.yml not found (Docker build) — skipping sync');
      process.exit(0);
    }
    throw e;
  }
  const doc = jsYaml.load(raw);
  const generated = buildFile(doc.majors);

  if (isCheck) {
    let current;
    try {
      current = await readFile(outPath, 'utf-8');
    } catch {
      console.error('[gen-categories] categories.ts not found. Run: npm run gen:categories');
      process.exit(1);
    }
    if (current.trimEnd() !== generated.trimEnd()) {
      console.error(
        '[gen-categories] DRIFT DETECTED: categories.ts is out of sync with categories.yml\n' +
        'Fix: npm run gen:categories && git add frontend/lib/constants/categories.ts'
      );
      process.exit(1);
    }
    console.log('[gen-categories] OK — categories.ts is in sync with categories.yml');
    return;
  }

  await writeFile(outPath, generated, 'utf-8');
  console.log(`[gen-categories] generated ${outPath}`);
}

run().catch(e => { console.error(e); process.exit(1); });
