/**
 * P0-4: OpenAPI → FE 타입 생성
 * BE Swagger(/v3/api-docs)에서 frontend/lib/types/api.ts를 자동 생성한다.
 * predev/prebuild 훅에서 실행. BE가 기동 중이 아니면 생성을 건너뛴다.
 */
import { writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(__dirname, '../lib/types/api.ts');
const apiDocsUrl = process.env.API_DOCS_URL || 'http://localhost:8080/v3/api-docs';

async function run() {
  let spec;
  try {
    const res = await fetch(apiDocsUrl, { signal: AbortSignal.timeout(5000) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    spec = await res.json();
  } catch (err) {
    console.warn(`[gen-api-types] BE not reachable (${err.message}) — skipping type generation`);
    process.exit(0);
  }

  const ast = await openapiTS(spec);
  const content = [
    '// AUTO-GENERATED by scripts/gen-api-types.mjs — do not edit manually',
    '// Run: npm run gen:types  (or starts automatically via predev)',
    '',
    astToString(ast),
  ].join('\n');

  await mkdir(resolve(__dirname, '../lib/types'), { recursive: true });
  await writeFile(outFile, content, 'utf-8');
  console.log(`[gen-api-types] generated ${outFile}`);
}

run();
