    /** 단일 조합 — 최대 9자 보장 (단어 풀이 큐레이션됨) */
    public static String generate() {
        ThreadLocalRandom rnd = ThreadLocalRandom.current();
        String mod = MODIFIERS.get(rnd.nextInt(MODIFIERS.size()));
        String creature = CREATURES.get(rnd.nextInt(CREATURES.size()));
        return mod + " " + creature;
    }

    /**
     * 중복 검사를 통과한 유니크한 닉네임 반환.
     * MAX_RETRY 회 실패 시 4자리 랜덤 숫자 첨부 (강제 유니크화 — 9자 초과 허용).
     *
     * @param isTaken 닉네임이 이미 사용 중이면 true 반환하는 검사 함수
     */
    public static String generateUnique(Predicate<String> isTaken) {
        for (int i = 0; i < MAX_RETRY; i++) {
            String candidate = generate();
            if (!isTaken.test(candidate)) return candidate;
        }
        // fallback: 형용사 + 생물 + 4자리 숫자 → 사실상 unique 보장
        ThreadLocalRandom rnd = ThreadLocalRandom.current();
        return generate() + " " + (1000 + rnd.nextInt(9000));
    }
